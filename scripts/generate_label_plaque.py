"""Generate a parametric OpenSCAD file for a physical (embossed-plastic,
not printed-paper) label plaque — a small mountable plate with a
container's code raised or recessed directly into the plastic, meant to
be glued or screwed onto larger objects the M110S pipeline doesn't
suit (a big shelf unit, a bought bin too large for its precut label
stock, anything you'd rather never re-label than trust an adhesive
sticker to hold for years).

Not the same idea as scripts/print_label.py's route (a 2D PNG printed on
adhesive label stock) — this is a standalone 3D part, sliced and printed
like any other hardware/ piece. Complementary to the bigger "bake the
code into a container's own SCAD/STL at generation time" idea (see
SPEC.md Parking Lot) — this is the version for objects that either
aren't 3D-printed themselves or already exist and just need a durable
tag added after the fact.

No OpenSCAD CLI in this environment (same as every other hardware/
file) — this writes the .scad source only. Open it in the real app to
render/validate before printing, same disclaimer as the rest of
hardware/.

Defaults to a debossed (recessed, open-topped) pocket rather than
embossed, because that's what a single-nozzle two-color print needs: an
open text-shaped pocket, not a capped-over emboss. Print the base in
your LIGHT color up to the pause height this script prints out, pause
and swap filament to BLACK, then resume for the remaining top layers —
that top color becomes the visible "background," and the light base
color only shows through the open letter-shaped pockets as the
lettering. One manual filament swap, no multi-material hardware
required. (Pass --emboss for the old single-color raised-text version
instead, if you don't want the two-tone look for a given plaque.)

Text width is ESTIMATED (a per-character mm allowance at the given font
size), not measured — OpenSCAD's actual glyph metrics aren't available
without invoking OpenSCAD itself. Good enough to size the plaque in the
right ballpark; if the rendered text overflows or leaves too much
margin, adjust --char-width-mm and regenerate rather than trusting this
blindly, same as this whole project's "good enough, verify once"
approach to hardware.

Usage:
    python generate_label_plaque.py TUB-01
    python generate_label_plaque.py AA-01-02 --deboss --screws --output hardware/generated/AA-01-02.scad
"""

import argparse
from pathlib import Path

SCAD_TEMPLATE = """\
// WheresDat — Physical label plaque for "{code}", generated by
// scripts/generate_label_plaque.py. Not yet rendered/validated (no
// OpenSCAD CLI in this environment) — open in the real app and test-fit
// before committing to a batch, same as the rest of hardware/.
//
// Text width is an ESTIMATE (char count x char_width_mm), not measured —
// see the script's own docstring. Re-generate with a different
// --char-width-mm if the rendered text doesn't fit the plate cleanly.

/* [Plate] */
plate_w        = {plate_w:.1f};  // mm — auto-sized to fit "{code}" at the estimate above, plus margin
plate_h        = {plate_h};    // mm
plate_thickness = {plate_thickness}; // mm — flat plate, prints trivially with no supports

/* [Text] */
code           = "{code}";
font_size      = {font_size};   // mm — nominal OpenSCAD text() size
text_depth     = {text_depth};  // mm — how far the text rises above (embossed) or cuts into (debossed) the plate face
emboss         = {emboss_bool};  // false (default): open, recessed text pocket — print the base in your LIGHT
                                  // filament, pause at the Z height this script prints out, swap to BLACK, and
                                  // resume: the swapped color becomes the background, light shows through the
                                  // open letter pockets as the lettering. true: raised text instead, single
                                  // color throughout (simpler, no filament swap, no two-tone look).

/* [Mounting] */
screw_holes    = {screws_bool};  // true: two countersunk holes for wood/self-tapping screws. false: flat back for gluing only.
screw_hole_dia = {screw_hole_dia}; // mm — through-hole diameter
screw_head_dia = {screw_head_dia}; // mm — countersink diameter at the back face
screw_head_depth = {screw_head_depth}; // mm — countersink depth, must be less than plate_thickness
screw_inset    = {screw_inset};  // mm from each short edge to its hole center

module plate() {{
    cube([plate_w, plate_h, plate_thickness]);
}}

module screw_hole(x) {{
    translate([x, plate_h / 2, -0.1])
        cylinder(h = plate_thickness + 0.2, d = screw_hole_dia, $fn = 24);
    // Countersink cut in from the BACK face (z=0) so the screw head sits flush.
    translate([x, plate_h / 2, -0.1])
        cylinder(h = screw_head_depth + 0.1, d = screw_head_dia, $fn = 24);
}}

module label_plaque() {{
    difference() {{
        union() {{
            plate();
            if (emboss)
                translate([plate_w / 2, plate_h / 2, plate_thickness])
                    linear_extrude(height = text_depth)
                        text(code, size = font_size, halign = "center", valign = "center", font = "Liberation Sans:style=Bold");
        }}
        union() {{
            if (!emboss)
                translate([plate_w / 2, plate_h / 2, plate_thickness - text_depth])
                    linear_extrude(height = text_depth + 0.1)
                        text(code, size = font_size, halign = "center", valign = "center", font = "Liberation Sans:style=Bold");
            if (screw_holes) {{
                screw_hole(screw_inset);
                screw_hole(plate_w - screw_inset);
            }}
        }}
    }}
}}

label_plaque();
"""


def generate_scad(
    code: str,
    font_size: float = 8.0,
    char_width_mm: float = 6.0,
    margin_mm: float = 6.0,
    plate_h: float = 20.0,
    plate_thickness: float = 3.0,
    text_depth: float = 0.8,
    emboss: bool = False,
    screws: bool = False,
    screw_hole_dia: float = 3.2,  # clears an M3 screw
    screw_head_dia: float = 6.0,
    screw_head_depth: float = 1.8,
) -> str:
    plate_w = len(code) * char_width_mm + 2 * margin_mm
    screw_inset = round(max(margin_mm, plate_w * 0.15), 2)
    return SCAD_TEMPLATE.format(
        code=code,
        plate_w=plate_w,
        plate_h=plate_h,
        plate_thickness=plate_thickness,
        font_size=font_size,
        text_depth=text_depth,
        emboss_bool="true" if emboss else "false",
        screws_bool="true" if screws else "false",
        screw_hole_dia=screw_hole_dia,
        screw_head_dia=screw_head_dia,
        screw_head_depth=screw_head_depth,
        screw_inset=screw_inset,
    )


def main():
    parser = argparse.ArgumentParser(description="Generate a physical (embossed-plastic) label plaque .scad for a WheresDat code")
    parser.add_argument("code", help="container code, e.g. TUB-01")
    parser.add_argument("--font-size", type=float, default=8.0, help="text size in mm (default: 8.0)")
    parser.add_argument("--char-width-mm", type=float, default=6.0, help="estimated mm per character at the given font size, used to size the plate (default: 6.0)")
    parser.add_argument("--margin-mm", type=float, default=6.0, help="margin on each side of the text, in mm (default: 6.0)")
    parser.add_argument("--plate-height", type=float, default=20.0, help="plate height in mm (default: 20.0)")
    parser.add_argument("--plate-thickness", type=float, default=3.0, help="plate thickness in mm (default: 3.0)")
    parser.add_argument("--text-depth", type=float, default=0.8, help="emboss/deboss depth in mm (default: 0.8)")
    parser.add_argument("--emboss", action="store_true", help="raise the text instead of recessing it -- single color throughout, no filament swap, no two-tone look")
    parser.add_argument("--screws", action="store_true", help="add two countersunk screw holes instead of a flat glue-only back")
    parser.add_argument("--output", default=None, help="output .scad path (default: hardware/generated/<code>.scad)")
    args = parser.parse_args()

    scad = generate_scad(
        args.code,
        font_size=args.font_size,
        char_width_mm=args.char_width_mm,
        margin_mm=args.margin_mm,
        plate_h=args.plate_height,
        plate_thickness=args.plate_thickness,
        text_depth=args.text_depth,
        emboss=args.emboss,
        screws=args.screws,
    )

    out_path = Path(args.output) if args.output else Path(__file__).resolve().parent.parent / "hardware" / "generated" / f"{args.code}.scad"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(scad, encoding="utf-8")
    print(f"Wrote {out_path}")

    if not args.emboss:
        pause_z = args.plate_thickness - args.text_depth
        print(
            f"\nTwo-color print: load LIGHT filament, print normally up to Z={pause_z:.2f}mm, "
            f"pause and swap to BLACK, then resume for the remaining {args.text_depth:.2f}mm "
            "(the top layers) to finish. Black becomes the background; light shows through "
            "the open letter pockets as the lettering."
        )


if __name__ == "__main__":
    main()
